"""Generate the human-readable review ledger from catalog-owned metadata."""
from catalog import ROOT, read, procedure_label, PROCEDURE_ROLES


def render(local):
    projects = sorted(local['projects'], key=lambda p: p['local']['name'].casefold())
    lines = ['# Independent repository reviews', '',
             f'This ledger covers {len(projects)} catalog-owned repository reviews. '
             'Evidence levels apply to each classification. Source review alone does not establish '
             'successful compilation or numerical verification. Specific local driver checks are identified '
             'explicitly; imported playground verification remains separate.', '',
             'Generated by `python xreviews.py` from `data/local.json`.', '',
             '| Repository | GAMS | Scope |', '| --- | --- | --- |']
    for project in projects:
        p = project['local']
        codes = ', '.join(dict.fromkeys(c['code'] for c in p.get('classifications', [])))
        lines.append(f'| [{p["name"]}]({p["repository"]["url"]}) | {codes} | {p["description"].replace("|", "&#124;")} |')
    for project in projects:
        p = project['local']
        lines.extend(['', '## '+p['name'], ''])
        if p.get('license'):
            license_data = p['license']
            lines.extend(['**License: '+(license_data.get('spdx_expression') or license_data['label'])+'**', '',
                          license_data['notes'], '',
                          f'Reviewed {license_data["reviewed_on"]} at `{license_data["revision"]}`.', ''])
            for evidence in license_data['evidence']:
                lines.extend([f'[{evidence["path"]}]({evidence["url"]})',
                              f'SHA-256 (normalized UTF-8/LF): `{evidence["sha256"]}`.', ''])
        for claim in p.get('classifications', []):
            lines.extend([f'**{claim["code"]} — {claim["level"]}**', '', claim['notes'], '',
                          f'Reviewed {claim["reviewed_on"]} at `{claim["revision"]}`.', ''])
            for evidence in claim['evidence']:
                lines.extend([f'[{evidence["path"]}]({evidence["url"]})',
                              f'SHA-256 (normalized UTF-8/LF): `{evidence["sha256"]}`.', ''])
                if evidence.get('source_encoding'):
                    lines.extend(['Original document encoding: '+evidence['source_encoding']+'.', ''])
            for procedure in claim.get('procedures', []):
                evidence = next(v for v in claim['evidence'] if v['path'] == procedure['path'])
                start, end = procedure['line_start'], procedure['line_end']
                role = PROCEDURE_ROLES.get(procedure.get('role'), 'Procedure')
                lines.extend([f'{role} `{procedure_label(procedure)}`: '
                              f'[{procedure["path"]}:{start}–{end}]({evidence["url"]}#L{start}-L{end}).', ''])
                if procedure.get('summary'):
                    lines.extend([procedure['summary'], ''])
                if procedure.get('signature'):
                    lines.extend(['Usage:', '', '```fortran', procedure['signature'], '```', ''])
                for name, label in (('declarations', 'Argument declarations'), ('examples', 'Author example (not run)')):
                    for reference in procedure.get(name, []):
                        source = next(v for v in claim['evidence'] if v['path'] == reference['path'])
                        first, last = reference['line_start'], reference['line_end']
                        lines.extend([f'{label}: [{reference["path"]}:{first}–{last}]({source["url"]}#L{first}-L{last}).', ''])
                if procedure.get('usage'):
                    driver = procedure.get('local_driver')
                    label = 'Locally checked main program:' if driver else 'Calling sketch (not a checked driver):'
                    lines.extend([label, '', '```fortran', procedure['usage'], '```', '', procedure['usage_notes'], ''])
                    if driver:
                        lines.extend([' ? '.join('['+title+'](../'+driver[field]+')' for field, title in (
                            ('path', 'Main program'), ('report', 'Saved numerical results'),
                            ('readme', 'Build instructions'), ('runner', 'Pinned-source runner'))), ''])
        if p.get('notes'):
            lines.extend([p['notes'], ''])
        if p.get('discovery'):
            lines.extend([f'[Pinned discovery list]({p["discovery"]["url"]}).', ''])
    return '\n'.join(lines).rstrip()+'\n'


if __name__ == '__main__':
    destination = ROOT/'docs/local-reviews.md'
    destination.write_text(render(read(ROOT/'data/local.json')), encoding='utf-8')
    print(destination)
